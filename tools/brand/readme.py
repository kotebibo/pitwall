"""Writes brand/README.md: one line per file with its size and where it is used."""
from __future__ import annotations

import re

from PIL import Image

import brandkit as bk

B = bk.BRAND

HEAD = """# Pit Wall brand kit

High-res pixel art, dark motorsport UI. Everything here is generated by
`tools/brand/` (`python tools/brand/build_all.py`, add `--render` to re-render
the 3D car with Godot) and is only ever scaled by whole numbers with nearest
filtering. Never resize these files with smooth filtering; pick the size that
fits, or scale by 2x/3x/4x with nearest neighbour.

- **Palette**: background `#141518`, panel `#1d1f23`, line `#34363c`, ink
  `#f1efea`, red `#e8352b` (brand), yellow `#f2c230`, purple `#a855f7`, blue
  `#5ec8e5`, green `#3ecf6a`. Logo shades: ink shade `#d9d5cc`, red highlight
  `#f2603f`, red low `#a8242a`, extrusion `#7a1a26`, outline `#0b0c0e`.
- **Type**: the PIT WALL wordmark is custom lettering (same pixels as the game's
  `ui/logo.png`). Body text is Pixelify Sans (the game's UI font) at 11 px with
  no antialiasing (7 px caps), scaled by whole numbers. Headlines such as
  "F1 + SOLANA" use the angular italic display face in `tools/brand/brandkit.py`.
- **Tagline**: DRIVE IT. RUN IT. PROVE IT. (drive the car, run the team, every
  lap verified on Solana).
- **Primary mark**: the PW monogram badge (`logo/logo_mark_*`). It has the UI
  panels' chamfered corners and the wordmark's speed stripe and chequer. 16, 24
  and 32 px are hand-placed, so use those files at those sizes.
- **Pixel scale**: large art is drawn at native size and scaled 3x (1080p class)
  or 4x (YouTube). The key art's native size is 640x360, which is the game's
  viewport.
- Colour logos are for dark backgrounds. On light backgrounds use `_black`; on
  red or photos use `_white`.

"""

SECTIONS = {
    "logo": "Logo system",
    "icons": "Favicons and app icons",
    "social": "Social and profile images",
    "keyart": "Key art and splash",
    "renders": "3D car renders (transparent)",
}


def describe(folder: str, name: str) -> str:
    n = name
    if folder == "logo":
        m = re.match(r"logo_wordmark(_white|_black)?_(\d)x", n)
        if m:
            v = {"": "full colour (dark backgrounds)", "_white": "one colour, ink (on red / photos / dark)",
                 "_black": "one colour, #141518 (light backgrounds, print)"}[m.group(1) or ""]
            return f"horizontal wordmark, {v}, {m.group(2)}x"
        if n.startswith("logo_wordmark_small"):
            return "compact wordmark (in-game logo_small), for tight UI spots"
        m = re.match(r"logo_stacked(_white|_black)?_(\d)x", n)
        if m:
            v = {"": "full colour", "_white": "one colour ink", "_black": "one colour dark"}[m.group(1) or ""]
            return f"stacked PIT / WALL for square spaces (posts, stickers, merch), {v}, {m.group(2)}x"
        m = re.match(r"logo_tagline(_white|_black)?_(\d)x", n)
        if m:
            v = {"": "full colour", "_white": "one colour ink", "_black": "one colour dark"}[m.group(1) or ""]
            return f"wordmark + tagline lockup (decks, site header, trailers), {v}, {m.group(2)}x"
        m = re.match(r"logo_mark_(\d+)\.png", n)
        if m:
            s = int(m.group(1))
            if s <= 32:
                return "primary mark, hand-placed pixel grid for this exact size (tiny UI, badges)"
            return "primary mark (PW badge) on transparent: UI, watermarks, stickers"
        if n.startswith("logo_mark_alt1"):
            return "alternate mark: the 3D car head-on on the red badge (best at 64 px and up)"
        if n.startswith("logo_mark_alt2"):
            return "alternate mark: italic P over the speed stripe on a dark badge"
        if n == "loading_logo.png":
            return "loading screen wordmark (2x wordmark centred on transparent)"
        if n == "loading_logo_128.png":
            return "loading screen small mark (spinner centre / corner)"
    if folder == "icons":
        if n.startswith("favicon_"):
            return "website favicon PNG (`<link rel=icon sizes=...>`), hand-placed at this size"
        if n == "favicon.ico":
            return "multi-size favicon (exact 16, 32 and 48 frames, no resampling) for /favicon.ico"
        if n.startswith("app_icon_512"):
            return "PWA / web manifest icon 512, full bleed (also works as `maskable`); Godot export icon"
        if n.startswith("app_icon_192"):
            return "PWA / web manifest icon 192, full bleed"
        if n.startswith("apple_touch"):
            return "iOS home screen icon (`apple-touch-icon`), full bleed, opaque"
    if folder == "social":
        if n.startswith("og_image"):
            return "link preview (`og:image` / `twitter:image`); content kept inside the central safe area"
        if n.startswith("x_banner"):
            return "X (Twitter) header; bottom-left ~400 px kept clear for the profile picture"
        if n.startswith("discord_banner"):
            return "Discord server banner / invite splash (16:9)"
        if n.startswith("youtube_thumb"):
            return "YouTube thumbnail: car + PIT WALL + F1 + SOLANA, readable small; bottom-right left for the timestamp"
        if n.startswith("avatar_car"):
            return "alternate profile picture: the 3D car on the night track (circle-safe)"
        if n.startswith("avatar_"):
            return "profile picture for X / Discord / Telegram: PW on red, reads as a tiny circle"
    if folder == "keyart":
        if n == "title_keyart_1920x1080.png":
            return "title screen / store key art with logo; left third kept calm for menu text"
        if n == "title_keyart_nologo_1920x1080.png":
            return "same without the logo (the game draws its own logo and menu)"
        if n == "title_keyart_640x360.png":
            return "native-pixel key art for the game's 640x360 viewport (drop-in for ui/bg_menu.png)"
        if n == "title_keyart_nologo_640x360.png":
            return "native-pixel key art without the logo, for the game"
        if n.startswith("boot_splash"):
            return "Godot boot splash (`application/boot_splash/image`), wordmark on #141518 at the game's 2x"
    if folder == "renders":
        m = re.match(r"car_(hero_left|hero|rear34|side|top|low_front)_(red|white|purple)(_3x|_shadow)?\.png", n)
        if m:
            ang = {"hero": "hero 3/4 front, nose right", "hero_left": "hero 3/4 front, nose left",
                   "rear34": "3/4 rear", "side": "side profile", "top": "top-down, nose up",
                   "low_front": "low dramatic front (perspective)"}[m.group(1)]
            liv = {"red": "brand red / ink", "white": "white / red", "purple": "purple / ink"}[m.group(2)]
            kind = {None: "native pixels", "_3x": "3x nearest", "_shadow": "contact-shadow layer (same box as the car)"}[m.group(3)]
            return f"3D car, {ang}, {liv} livery, {kind}"
    return ""


def build():
    lines = [HEAD]
    for folder, title in SECTIONS.items():
        d = B / folder
        files = sorted(p for p in d.iterdir() if p.is_file())
        lines.append(f"## {folder}/  ({title})\n")
        for p in files:
            try:
                with Image.open(p) as im:
                    size = f"{im.width}x{im.height}"
            except Exception:
                size = "?"
            if p.suffix == ".ico":
                size = "16+32+48"
            lines.append(f"- `{p.name}` {size}: {describe(folder, p.name)}")
        lines.append("")
    lines.append("## brand_sheet.png\n")
    with Image.open(B / "brand_sheet.png") as im:
        lines.append(f"- `brand_sheet.png` {im.width}x{im.height}: contact sheet of the whole kit")
    lines.append("")
    lines.append("`renders/_src/` holds the raw Godot output (with camera JSON) that the generators compose from.")
    lines.append("Render script: `game/scenes/car3d/render_brand.gd`; generators: `tools/brand/`.\n")
    (B / "README.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    build()
    print("wrote", B / "README.md")
